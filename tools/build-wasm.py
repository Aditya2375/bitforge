"""Build the original C core into a static, embedded WebAssembly module."""

import base64
import os
from pathlib import Path
import shutil
import subprocess

root = Path(__file__).resolve().parent.parent
compiler = os.environ.get("WASM_CC") or shutil.which("clang")
if not compiler:
    raise SystemExit("Set WASM_CC to a clang with wasm32 support (LLVM or Emscripten).")
exports = "reset reg pc status tval retired byte_at poke step field".split()
(root / "build").mkdir(exist_ok=True)
cmd = [
    compiler,
    "--target=wasm32",
    "-std=c11",
    "-O2",
    "-fno-builtin",
    "-nostdlib",
    "-Wl,--no-entry",
    "-Wl,--strip-all",
    "-Wl,--initial-memory=196608",
    "-Wl,--max-memory=196608",
]
cmd += ["-Wl,--export=" + x for x in exports]
cmd += ["src/machine.c", "src/bridge.c", "-o", "build/bitforge.wasm"]
subprocess.run(cmd, cwd=root, check=True)
binary = (root / "build/bitforge.wasm").read_bytes()
(root / "docs/core.js").write_text(
    "// Generated by tools/build-wasm.py from src/machine.c and src/bridge.c.\nexport const bytes=Uint8Array.from(atob("
    + repr(base64.b64encode(binary).decode())
    + "),c=>c.charCodeAt(0));\n"
)
print(f"{len(binary)} byte WASM, embedded in docs/core.js")
